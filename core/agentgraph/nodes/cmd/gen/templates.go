package main

// Templates for attrs_gen.go and wire_gen.go.
//
// Style choices that protect idempotency (FR-009 / NFR-004):
//   - All ranges iterate over slices we sorted in main.go; no map
//     iteration order leaks into the output.
//   - We avoid `goimports` and rely on go/format alone, so we declare
//     every needed import explicitly when populated (and emit none when
//     the file has no callable kinds).
//   - Empty-catalog mode emits a fixed banner so the file is still a
//     valid Go source — `package agentgraph` plus a comment.
//
// The wire template emits the following symbols (all package-level):
//   - NodeKind<X> NodeKind   constants
//   - AllNodeKinds []NodeKind
//   - decodeAttrs(kind, raw, nodeID) (NodeAttrs, error)
//   - defaultAttrsFor(kind) NodeAttrs
//   - ResolvedManifests map[NodeKind]*nodes.ResolvedManifest (init'd)
//
// As of WP04 the generator emits the canonical names directly:
// `NodeKindX`, `AllNodeKinds`, `decodeAttrs`, `defaultAttrsFor`,
// `defaultPortsFor`. The hand-written attrs.go and wire.go are deleted;
// these generated files are now the single source of truth.

// manifestVersionsTemplate emits manifest_versions_gen.go — a separate file
// (not attrs_gen.go) to minimise merge conflicts with the typed-port-codegen
// sister mission that extends attrs_gen.go / wire_gen.go.
//
// Emitted symbols per callable kind:
//
//	<GoName>ManifestVersion   string  — semver from manifest_version: field
//	<GoName>ManifestFingerprint string — sha256 hex of behavior-affecting subset
