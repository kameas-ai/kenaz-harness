// Command gen is the agentgraph node-catalog codegen tool. It reads
// every shipped + user manifest via nodes.LoadCatalog, resolves the
// inheritance chains, and emits two files into core/agentgraph:
//
//   - attrs_gen.go : one <KindPascal>Attrs struct per callable kind,
//     implementing the NodeAttrs interface (zero-arg
//     nodeAttrsMarker() + manifest-driven Validate()).
//   - wire_gen.go  : NodeKind* constants, AllNodeKinds slice,
//     decodeAttrs switch, defaultAttrsFor, and the
//     ResolvedManifests registry populated at init.
//
// The generator is byte-equal idempotent: running it twice produces
// identical bytes. Generated files carry the canonical
// "Code generated ... DO NOT EDIT." header and run through go/format
// for stable formatting.
//
// In WP02 the shipped catalog contains only archetype manifests (no
// callable kinds yet). The generator therefore emits essentially-empty
// _gen.go files; the value in WP02 is the tool itself plus the CI
// gate. WP04 lands kind manifests and the generated files populate.
//
// Mission: agent-kernel-graph-node-catalog-01KQ7JDZ, WP02.
// FR refs: FR-008..FR-012, NFR-004 (idempotency), NFR-008 (stdlib only).
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
	"unicode"

	"github.com/sigil-tech/kaneaz-harness/core/agentgraph/nodes"
)

const (
	// generatedHeader is the canonical first line of every generated
	// file (FR-010). Tools and humans grep for "DO NOT EDIT" to skip.
	generatedHeader = "// Code generated by agentgraph/nodes/cmd/gen; DO NOT EDIT."
)

// genConfig collects CLI inputs for the generator. Defaults align with
// the //go:generate directive's working directory at
// core/agentgraph/, so a manifest at core/agentgraph/nodes/manifests/
// resolves correctly when invoked through `go generate`.
type genConfig struct {
	// outDir is the directory the two generated files land in.
	outDir string
	// userDir is the optional <DataDir>/agent_graph/nodes override
	// directory. Empty means "no user overrides", which is the normal
	// build-time invocation; tests may pass a fixture dir.
	userDir string
	// fixtureDir, when non-empty, replaces the embedded shipped manifests.
	// Test-only — production runs leave this empty so the embedded set is
	// the source of truth.
	fixtureDir string
	// pkgName is the Go package name written into the generated files.
	// Defaults to "agentgraph".
	pkgName string
}

func main() {
	cfg := parseFlags()
	if err := run(cfg); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

func parseFlags() genConfig {
	cfg := genConfig{
		outDir:  ".",
		pkgName: "agentgraph",
	}
	flag.StringVar(&cfg.outDir, "out", cfg.outDir, "directory the generated files land in")
	flag.StringVar(&cfg.userDir, "user-dir", "", "optional user override directory")
	flag.StringVar(&cfg.fixtureDir, "fixture-dir", "", "test-only: read manifests from this directory instead of the embedded set")
	flag.StringVar(&cfg.pkgName, "package", cfg.pkgName, "Go package name written into the generated files")
	flag.Parse()
	return cfg
}

func run(cfg genConfig) error {
	cat, err := loadCatalog(cfg)
	if err != nil {
		return fmt.Errorf("load catalog: %w", err)
	}
	kinds := selectCallable(cat)

	attrsBytes, err := renderAttrs(cfg.pkgName, kinds)
	if err != nil {
		return fmt.Errorf("render attrs: %w", err)
	}
	wireBytes, err := renderWire(cfg.pkgName, kinds)
	if err != nil {
		return fmt.Errorf("render wire: %w", err)
	}

	attrsPath := filepath.Join(cfg.outDir, "attrs_gen.go")
	wirePath := filepath.Join(cfg.outDir, "wire_gen.go")
	if err := writeFile(attrsPath, attrsBytes); err != nil {
		return fmt.Errorf("write %s: %w", attrsPath, err)
	}
	if err := writeFile(wirePath, wireBytes); err != nil {
		return fmt.Errorf("write %s: %w", wirePath, err)
	}
	return nil
}

// loadCatalog hides the fixture-vs-embedded toggle. Production runs
// leave fixtureDir empty so the embedded set wins; tests pass a fixture
// dir and skip the embedded set so the generator processes only the
// hand-crafted manifests.
func loadCatalog(cfg genConfig) (*nodes.Catalog, error) {
	if cfg.fixtureDir != "" {
		return nodes.LoadCatalog(nodes.LoadOptions{
			SkipBundled: true,
			UserDir:     cfg.fixtureDir,
		})
	}
	return nodes.LoadCatalog(nodes.LoadOptions{UserDir: cfg.userDir})
}

// selectCallable returns the catalog's callable kinds in deterministic
// order (sorted by ID — FR-009 / NFR-004 idempotency).
func selectCallable(cat *nodes.Catalog) []*nodes.ResolvedManifest {
	all := cat.Kinds() // already sorted by ID per Catalog.Kinds() / List()
	out := make([]*nodes.ResolvedManifest, 0, len(all))
	for _, rm := range all {
		if rm == nil || !rm.Manifest.IsCallable() {
			continue
		}
		out = append(out, rm)
	}
	// Belt-and-braces: re-sort by ID so future Catalog reorderings cannot
	// break idempotency.
	sort.SliceStable(out, func(i, j int) bool {
		return out[i].Manifest.ID < out[j].Manifest.ID
	})
	return out
}

// writeFile writes deterministic bytes to a file. Pre-existing content
// is overwritten. We strip trailing whitespace per line and end with a
// single newline so re-runs do not flap on different platforms.
func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

// ---- Template data shapes ----

// attrField is one resolved attribute, ready for template emission.
type attrField struct {
	GoName    string // PascalCase Go field name
	JSONField string // snake_case wire name
	GoType    string // Go type literal (e.g., "string", "int", "[]string", "map[string]any")
	AttrName  string // original attr-map key (for validator error messages)
	Comment   string // optional description, line-wrapped for the doc-comment

	// Constraint metadata used by the generated Validate() body.
	Required        bool
	HasMin          bool
	Min             float64
	HasMax          bool
	Max             float64
	HasMinLength    bool
	MinLength       int
	HasMaxLength    bool
	MaxLength       int
	Enum            []string
	IsString        bool
	IsNumeric       bool // numeric (int or float)
	IsInt           bool
	IsFloat         bool
	IsArray         bool
	IsBool          bool
	IsEnum          bool
	IsPointerNumber bool // ptr type used for nullable numeric (e.g. *float64)
}

// portField is one resolved port (input or output), ready for template
// emission into the generated `defaultPortsFor` switch.
type portField struct {
	Name     string
	Type     string // PortType literal (e.g., "messages", "any")
	Required bool
}

// kindData is one callable kind, ready for template emission.
type kindData struct {
	ID         string // canonical ID (e.g., "history_read")
	GoName     string // PascalCase struct prefix (e.g., "HistoryRead")
	StructName string // <GoName>Attrs
	ConstName  string // NodeKind<GoName>
	KindName   string // on-the-wire NodeKind value
	Aliases    []string
	Doc        string // doc-comment for the struct
	Fields     []attrField
	Inputs     []portField
	Outputs    []portField
}

// fileData is the top-level template input.
type fileData struct {
	Package string
	Header  string
	Kinds   []kindData
}

// ---- Rendering ----

func renderAttrs(pkg string, kinds []*nodes.ResolvedManifest) ([]byte, error) {
	data, err := buildFileData(pkg, kinds)
	if err != nil {
		return nil, err
	}
	tmpl, err := template.New("attrs").Funcs(tmplFuncs).Parse(attrsTemplate)
	if err != nil {
		return nil, err
	}
	var sb strings.Builder
	if err := tmpl.Execute(&sb, data); err != nil {
		return nil, err
	}
	return formatGo(sb.String())
}

func renderWire(pkg string, kinds []*nodes.ResolvedManifest) ([]byte, error) {
	data, err := buildFileData(pkg, kinds)
	if err != nil {
		return nil, err
	}
	tmpl, err := template.New("wire").Funcs(tmplFuncs).Parse(wireTemplate)
	if err != nil {
		return nil, err
	}
	var sb strings.Builder
	if err := tmpl.Execute(&sb, data); err != nil {
		return nil, err
	}
	return formatGo(sb.String())
}

func buildFileData(pkg string, kinds []*nodes.ResolvedManifest) (fileData, error) {
	out := fileData{
		Package: pkg,
		Header:  generatedHeader,
		Kinds:   make([]kindData, 0, len(kinds)),
	}
	for _, rm := range kinds {
		kd, err := buildKindData(rm)
		if err != nil {
			return fileData{}, fmt.Errorf("kind %q: %w", rm.Manifest.ID, err)
		}
		out.Kinds = append(out.Kinds, kd)
	}
	return out, nil
}

func buildKindData(rm *nodes.ResolvedManifest) (kindData, error) {
	id := rm.Manifest.ID
	goName := pascalCase(id)
	// Resolve the on-the-wire NodeKind value. The resolver pre-fills
	// KindName from the root-archetype layer (a known artefact of the
	// inheritance walk), so we only honour KindName when it differs
	// from any name in the chain — otherwise we fall back to the
	// leaf's ID which is always correct.
	kindName := rm.Manifest.KindName
	if kindName == "" || isAncestorName(kindName, rm.Chain) {
		kindName = id
	}
	kd := kindData{
		ID:         id,
		GoName:     goName,
		StructName: goName + "Attrs",
		ConstName:  "NodeKind" + goName,
		KindName:   kindName,
		Aliases:    append([]string(nil), rm.Manifest.Aliases...),
		Doc:        rm.Manifest.Description,
	}
	for _, p := range rm.Manifest.Ports.Inputs {
		kd.Inputs = append(kd.Inputs, portField{Name: p.Name, Type: p.Type, Required: p.Required})
	}
	for _, p := range rm.Manifest.Ports.Outputs {
		kd.Outputs = append(kd.Outputs, portField{Name: p.Name, Type: p.Type, Required: p.Required})
	}

	// Sort attr names for deterministic emission (FR-009).
	names := make([]string, 0, len(rm.Manifest.Attrs))
	for name := range rm.Manifest.Attrs {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		spec := rm.Manifest.Attrs[name]
		f, err := buildAttrField(name, spec)
		if err != nil {
			return kindData{}, fmt.Errorf("attr %q: %w", name, err)
		}
		kd.Fields = append(kd.Fields, f)
	}
	return kd, nil
}

func buildAttrField(name string, spec nodes.AttrSpec) (attrField, error) {
	goName := spec.GoField
	if goName == "" {
		goName = pascalCase(name)
	}
	jsonField := spec.JSONField
	if jsonField == "" {
		jsonField = name
	}
	goType, isPtrNum, err := goTypeFor(spec)
	if err != nil {
		return attrField{}, err
	}
	f := attrField{
		GoName:          goName,
		JSONField:       jsonField,
		GoType:          goType,
		AttrName:        name,
		Comment:         spec.Description,
		Required:        spec.Required,
		IsPointerNumber: isPtrNum,
	}
	if spec.Min != nil {
		f.HasMin = true
		f.Min = *spec.Min
	}
	if spec.Max != nil {
		f.HasMax = true
		f.Max = *spec.Max
	}
	if spec.MinLength != nil {
		f.HasMinLength = true
		f.MinLength = *spec.MinLength
	}
	if spec.MaxLength != nil {
		f.HasMaxLength = true
		f.MaxLength = *spec.MaxLength
	}
	if len(spec.Enum) > 0 {
		f.Enum = append([]string(nil), spec.Enum...)
	}
	switch spec.Type {
	case nodes.AttrTypeString, nodes.AttrTypeModelRef, nodes.AttrTypeToolRef,
		nodes.AttrTypeActivityRef, nodes.AttrTypeCorpusRef,
		nodes.AttrTypeAttachmentRef, nodes.AttrTypeNodeIDRef,
		nodes.AttrTypePortRef, nodes.AttrTypeMessagesRef:
		f.IsString = true
	case nodes.AttrTypeInt:
		f.IsInt = true
		f.IsNumeric = true
	case nodes.AttrTypeFloat:
		f.IsFloat = true
		f.IsNumeric = true
	case nodes.AttrTypeBool:
		f.IsBool = true
	case nodes.AttrTypeArray, nodes.AttrTypeStringSlice:
		f.IsArray = true
	case nodes.AttrTypeEnum:
		f.IsEnum = true
		f.IsString = true
	}
	return f, nil
}

// goTypeFor maps an AttrType to the Go type literal we emit on the
// generated struct's field.
//
//   - string-shaped refs all collapse to `string` because the typed
//     ref is enforced by the validator (model_ref, tool_ref, etc).
//   - numeric types lower to `int` or `float64`. Bare numerics are
//     used (no *int / *float64); a future WP can introduce nullable
//     numerics if the manifest declares them.
//   - array of strings is `[]string`; opaque arrays land as `[]any`.
//   - object/map types land as `map[string]any` to match the
//     ModelAttrs.JsonSchema / ToolAttrs.Args shape.
//
// Returns (goType, isPointerNumeric, err).
func goTypeFor(spec nodes.AttrSpec) (string, bool, error) {
	switch spec.Type {
	case nodes.AttrTypeString, nodes.AttrTypeEnum,
		nodes.AttrTypeModelRef, nodes.AttrTypeToolRef,
		nodes.AttrTypeActivityRef, nodes.AttrTypeCorpusRef,
		nodes.AttrTypeAttachmentRef, nodes.AttrTypeNodeIDRef,
		nodes.AttrTypePortRef, nodes.AttrTypeMessagesRef,
		nodes.AttrTypeDuration:
		return "string", false, nil
	case nodes.AttrTypeInt:
		return "int", false, nil
	case nodes.AttrTypeFloat:
		return "float64", false, nil
	case nodes.AttrTypeBool:
		return "bool", false, nil
	case nodes.AttrTypeArray, nodes.AttrTypeStringSlice:
		return "[]string", false, nil
	case nodes.AttrTypeObject, nodes.AttrTypeMap:
		return "map[string]any", false, nil
	case "":
		return "", false, fmt.Errorf("missing type")
	default:
		return "", false, fmt.Errorf("unknown attr type %q", spec.Type)
	}
}

// isAncestorName reports whether candidate matches any element in the
// inheritance chain other than the leaf (the last entry). Used by the
// codegen to ignore KindName values the resolver propagated from a
// parent archetype.
func isAncestorName(candidate string, chain []string) bool {
	if len(chain) <= 1 {
		return false
	}
	leaf := chain[len(chain)-1]
	for _, ancestor := range chain {
		if ancestor == leaf {
			continue
		}
		if ancestor == candidate {
			return true
		}
	}
	return false
}

// pascalCase converts kebab/snake/space-separated identifiers to
// PascalCase. We walk runes once so multi-byte input is safe; tokens
// like "id", "json", "url" come out un-acronymized (Id, Json, Url) on
// purpose — manifests can opt-in to acronym uppercasing on a
// per-attr basis via `go_field:` (e.g. set `go_field: JSONSchema`).
// The default is
// the simpler PascalCase, and authors are free to set go_field for any
// attr that needs the all-caps acronym treatment.
func pascalCase(s string) string {
	if s == "" {
		return ""
	}
	var b strings.Builder
	upNext := true
	for _, r := range s {
		switch {
		case r == '_' || r == '-' || r == ' ' || r == '.':
			upNext = true
		case upNext:
			b.WriteRune(unicode.ToUpper(r))
			upNext = false
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// formatGo runs the rendered template through go/format. Output is
// always LF-terminated (gofmt enforces).
func formatGo(src string) ([]byte, error) {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		// Surface the un-formatted source so test failures show what
		// the template produced.
		return nil, fmt.Errorf("format.Source: %w\n--- source ---\n%s", err, src)
	}
	return formatted, nil
}

// ---- Templates ----

// tmplFuncs are exposed to text/template. Kept tiny so templates stay
// readable.
var tmplFuncs = template.FuncMap{
	"backtick": func() string { return "`" },
	"goString": goString,
	"join":     strings.Join,
}

// goString emits a Go string literal for an arbitrary string. We use
// %q so embedded quotes / backslashes round-trip safely.
func goString(s string) string {
	return fmt.Sprintf("%q", s)
}
