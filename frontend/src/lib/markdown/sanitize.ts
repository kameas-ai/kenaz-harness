export function sanitize(html: string, profile: SanitizeProfile = 'default'): string {
  if (profile === 'katex') {
    return DOMPurify.sanitize(html, {
      ...BASE_CONFIG,
      ADD_TAGS: KATEX_EXTRA_TAGS,
      ADD_ATTR: [...(BASE_CONFIG!.ADD_ATTR as string[]), ...KATEX_EXTRA_ATTRS],
      RETURN_DOM_FRAGMENT: false,
      RETURN_DOM: false,
    }) as string;
  }

  if (profile === 'mermaid-svg') {
    return DOMPurify.sanitize(html, {
      ...BASE_CONFIG,
      ADD_TAGS: SVG_EXTRA_TAGS,
      ADD_ATTR: [...(BASE_CONFIG!.ADD_ATTR as string[]), ...SVG_EXTRA_ATTRS],
      FORBID_TAGS: ['foreignObject', 'script', 'iframe'],
      RETURN_DOM_FRAGMENT: false,
      RETURN_DOM: false,
    }) as string;
  }

  // default — GFM HTML only
  return DOMPurify.sanitize(html, {
    ...BASE_CONFIG,
    RETURN_DOM_FRAGMENT: false,
    RETURN_DOM: false,
  }) as string;
}
