/**
 * sanitize — DOMPurify wrapper with per-renderer profiles.
 *
 * Usage:
 *   sanitize(html)                  // default profile (GFM)
 *   sanitize(html, 'katex')         // allows KaTeX class names + MathML
 *   sanitize(html, 'mermaid-svg')   // allows SVG, forbids <foreignObject>
 *
 * Security boundary: every path through MarkdownBlock.vue must call
 * sanitize before inserting into v-html. DOMPurify is the load-bearing
 * XSS guard — never bypass it.
 */
import DOMPurify from 'dompurify';

export type SanitizeProfile = 'default' | 'katex' | 'mermaid-svg';

type DomPurifyConfig = Parameters<typeof DOMPurify.sanitize>[1];

/** Tags DOMPurify allows in its default set that we always keep. */
const BASE_CONFIG: DomPurifyConfig = {
  ADD_ATTR: [
    'target',
    'rel',
    'class',
    'data-md-block',
    'data-md-mention',
    'data-lang',
    'data-source-b64',
  ],
  // F-005 (v0.17.0 security audit): block inline style attributes on all
  // sanitized HTML. DOMPurify's default allowlist includes `style` on
  // standard elements (<span>, <p>, …); leaving it allowed lets LLM-
  // controlled CSS inject phishing overlays / exfil via background-image.
  // FORBID_ATTR overrides ADD_ATTR so SVG profiles that add `style` back
  // (mermaid output) are also blocked here — accept the trade-off; the
  // safe rendering path is class names from tokens.css, not inline CSS.
  FORBID_ATTR: ['style'],
};

