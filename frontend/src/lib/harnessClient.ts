function wailsBindings(): WailsBindingsLike {
  const b = (typeof window !== 'undefined' && window.go?.rpc?.Bindings) || undefined;
  if (!b) {
    throw new Error(
      'window.go.rpc.Bindings is not available. The harness frontend must run inside Wails.',
    );
  }
  return b;
}

