export interface SessionsClient {
  list(): Promise<Session[]>;
  get(id: string): Promise<Session>;
  create(name: string): Promise<Session>;
  rename(id: string, name: string): Promise<void>;
  delete(id: string): Promise<void>;
  reorder(ids: string[]): Promise<void>;
  startStream(id: string): Promise<string>;
  stopStream(subscriptionId: string): Promise<void>;

  /**
   * listMessages returns the chat-message history for a session in
   * append-order. Pagination lands when long-context replays do; for now
   * the full transcript is returned.
   */
  listMessages(id: string): Promise<Message[]>;
  /**
   * appendMessage commits a single message to the session transcript and
   * returns the canonical Message (with server-assigned id + createdAt).
   * The Go side enforces redaction policy before persistence.
   */
  appendMessage(
    id: string,
    role: MessageRole,
    content: string,
  ): Promise<Message>;
  /** Persist a draft input for the session (debounced caller). */
  saveDraft(id: string, draft: string): Promise<void>;
  /** Load the persisted draft (empty string if none). */
  loadDraft(id: string): Promise<string>;
  /**
   * Persist the per-session starting context (Mission A). kind is
   * 'system' (invisible system prompt prepended on every send) or
   * 'user_seed' (visible — caller is responsible for ALSO appending
   * the content as a user message via appendMessage). The Go side
   * validates kind and rejects unknown values.
   */
  setSystemPrompt(
    id: string,
    content: string,
    kind: 'system' | 'user_seed',
  ): Promise<void>;
  /**
   * moveToProject sets the session's project membership. Empty
   * projectId detaches the session and makes it loose.
   */
  moveToProject(id: string, projectId: string): Promise<void>;
}

/**
 * ProjectsClient — top-level Project entity CRUD + session membership.
 * Projects group related sessions; sessions outside a project are loose.
 */
export interface ProjectsClient {
  list(): Promise<Project[]>;
  get(id: string): Promise<Project>;
  create(name: string, description?: string): Promise<Project>;
  rename(id: string, name: string): Promise<void>;
  updateDescription(id: string, description: string): Promise<void>;
  /**
   * remove deletes the project. When deleteSessions=true, every
   * session attached to the project is deleted as part of the same
   * operation; otherwise sessions become loose.
   */
  remove(id: string, deleteSessions: boolean): Promise<void>;
  addSession(projectId: string, sessionId: string): Promise<void>;
  removeSession(sessionId: string): Promise<void>;
  listSessions(projectId: string): Promise<Session[]>;
}

export interface LLMConnectorClient {
  listProviders(): Promise<Provider[]>;
  /**
   * startStream begins an assistant completion against `profileID` for
   * `sessionID`. modelOverride (optional) selects a non-default model
   * from the profile's authorised set — the backend validates and
   * substitutes it into the request. Returns the subscription id used
   * by `stopStream` and as the correlation key on `llm:stream-chunk`
   * events.
   */
  startStream(
    profileID: string,
    sessionID: string,
    modelOverride?: string,
  ): Promise<string>;
  stopStream(id: string): Promise<void>;
  /**
   * AddProvider persists a personal provider profile. The plaintextApiKey,
   * if supplied, is written to the OS keychain by the backend and zeroed
   * before any further processing. Only the CredentialReference enters
   * providers.json.
   */
  addProvider(input: AddProviderInput): Promise<void>;
  /**
   * UpdateProvider replaces an existing personal provider profile.
   * plaintextApiKey is OPTIONAL — when omitted, the keychain entry
   * is left in place so the user can edit model/region without
   * re-entering their credential.
   */
  updateProvider(input: AddProviderInput): Promise<void>;
  removeProvider(id: string): Promise<void>;
  testProvider(id: string): Promise<TestResult>;
  /**
   * Probe the provider for the set of models the supplied API key is
   * authorized to call. Returns an empty list when the kind has no
   * adapter or no /models endpoint — UI should fall back to manual
   * model entry in that case.
   */
  listModels(kind: string, plaintextApiKey: string): Promise<ModelInfo[]>;
}

