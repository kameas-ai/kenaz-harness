/**
 * WireArtifactWithBytes — Wails-generated shape for `Artifacts_Get`.
 * The autogenerated TS calls `bytes` a `number[]`, but the runtime
 * payload is a base64 string (Go-side `[]byte` → JSON base64). We
 * normalise to a `string` in the typed `ArtifactWithBytes` surface.
 */
interface WireArtifactWithBytes {
  artifact: Artifact;
  bytes: unknown;
}

function adaptArtifactBytes(raw: unknown): string {
  if (typeof raw === 'string') return raw;
  // Defensive: the Wails generator sometimes types []byte as number[];
  // if a number array slips through, base64-encode it on the fly.
  if (Array.isArray(raw)) {
    let bin = '';
    for (const n of raw) {
      if (typeof n === 'number') bin += String.fromCharCode(n & 0xff);
    }
    return typeof btoa === 'function' ? btoa(bin) : '';
  }
  return '';
}

interface WireRecipeListing {
  recipe: WireRecipe;
  enabled: boolean;
  status: WireRecipeStatus;
  keysPresent: boolean;
}

const KNOWN_CATEGORIES: readonly RecipeCategory[] = [
  'search',
  'filesystem',
  'memory',
  'fetch',
  'other',
];

function adaptCategory(raw: string): RecipeCategory {
  return (KNOWN_CATEGORIES as readonly string[]).includes(raw)
    ? (raw as RecipeCategory)
    : 'other';
}

const KNOWN_STATES: readonly RecipeState[] = [
  'stopped',
  'starting',
  'running',
  'restarting',
  'failed',
];

function adaptState(raw: string): RecipeState {
  return (KNOWN_STATES as readonly string[]).includes(raw)
    ? (raw as RecipeState)
    : 'stopped';
}

function adaptEnvKey(w: WireEnvKey): EnvKey {
  return {
    name: w.name,
    display: w.display,
    docsUrl: w.docs_url || undefined,
    required: w.required,
  };
}

const KNOWN_CONFIG_KINDS: readonly ConfigKind[] = [
  'directory_list',
  'boolean',
  'string',
];

function adaptConfigKind(raw: string): ConfigKind {
  return (KNOWN_CONFIG_KINDS as readonly string[]).includes(raw)
    ? (raw as ConfigKind)
    : 'string';
}

function adaptConfigOption(w: WireConfigOption): ConfigOption {
  return {
    name: w.name,
    display: w.display,
    kind: adaptConfigKind(w.kind),
    default: w.default,
    required: w.required,
    description: w.description,
  };
}

function adaptRecipe(w: WireRecipe): Recipe {
  const configOptions = w.config_options
    ? w.config_options.map(adaptConfigOption)
    : undefined;
  return {
    id: w.id,
    displayName: w.display_name,
    description: w.description,
    category: adaptCategory(w.category),
    envKeys: (w.env_keys ?? []).map(adaptEnvKey),
    capabilities: w.capabilities,
    docsUrl: w.docs_url || undefined,
    argsTemplate: w.args_template ? [...w.args_template] : undefined,
    configOptions,
  };
}

function adaptRecipeStatus(w: WireRecipeStatus): RecipeStatus {
  return {
    id: w.id,
    enabled: w.enabled,
    state: adaptState(w.state),
    lastError: w.last_error || undefined,
    restartAttempts: w.restart_attempts,
    keysPresent: w.keys_present,
    pid: w.pid,
    protocolVersion: w.protocol_version || undefined,
    serverName: w.server_name || undefined,
    serverVersion: w.server_version || undefined,
    toolCount: w.tool_count,
    resourceCount: w.resource_count,
    promptCount: w.prompt_count,
    stderrTail: w.stderr_tail || undefined,
  };
}

function adaptRecipeListing(w: WireRecipeListing): RecipeListing {
  return {
    recipe: adaptRecipe(w.recipe),
    enabled: w.enabled,
    status: adaptRecipeStatus(w.status),
    keysPresent: w.keysPresent,
  };
}

