/**
 * harnessClient — the typed wrapper over `window.go.rpc.Bindings`.
 *
 * This is the ONLY module that knows about the Wails-generated surface.
 * Components and composables consume the nested view-scoped client objects
 * (e.g., `client.sessions.list()`); ESLint forbids `wailsjs/*` imports
 * outside this file (FR-007 / C-001 / plan §4.1).
 *
 * The Wails-generated bindings live under `frontend/wailsjs/go/rpc/Bindings`
 * once `wails generate module` runs against the `Bindings` struct. Until
 * regeneration, `WailsBindings` resolves through the runtime-attached
 * `window.go.rpc.Bindings` object Wails injects at boot. Both paths flow
 * through the same `WailsBindingsLike` interface so swapping in a fake
 * client is purely a TypeScript concern.
 */

